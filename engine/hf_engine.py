import time
import asyncio
import threading
from typing import AsyncGenerator, Optional
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer, TextIteratorStreamer

from engine.base import BaseEngine

class HFEngine(BaseEngine):
    """
    Production-grade local LLM inference engine using HuggingFace Transformers.
    Performs true autoregressive token generation with streaming output.
    """
    
    def __init__(self, model_name: str = "Qwen/Qwen2.5-0.5B-Instruct", device: Optional[str] = None):
        self.model_name = model_name
        self.device = device or ("cuda" if torch.cuda.is_available() else "cpu")
        
        print(f"[HFEngine] Initializing tokenizer & model: {self.model_name} on {self.device}...")
        self.tokenizer = AutoTokenizer.from_pretrained(self.model_name)
        if self.tokenizer.pad_token is None:
            self.tokenizer.pad_token = self.tokenizer.eos_token
            
        self.model = AutoModelForCausalLM.from_pretrained(
            self.model_name,
            torch_dtype=torch.float32 if self.device == "cpu" else torch.float16
        ).to(self.device)
        self.model.eval()
        print(f"[HFEngine] Model loaded successfully on {self.device}.")

    async def generate_stream(
        self, 
        prompt: str, 
        max_tokens: int = 150,
        temperature: float = 0.7,
        top_p: float = 0.9
    ) -> AsyncGenerator[str, None]:
        """
        Asynchronously streams tokens generated by the model without blocking the event loop.
        """
        if max_tokens <= 0:
            return
        # Format with chat template if available for optimal instruct quality
        if hasattr(self.tokenizer, "apply_chat_template") and self.tokenizer.chat_template:
            messages = [{"role": "user", "content": prompt}]
            formatted_input = self.tokenizer.apply_chat_template(
                messages, 
                tokenize=False, 
                add_generation_prompt=True
            )
        else:
            formatted_input = prompt

        inputs = self.tokenizer(formatted_input, return_tensors="pt").to(self.device)
        input_ids = inputs["input_ids"]

        streamer = TextIteratorStreamer(
            self.tokenizer, 
            skip_prompt=True, 
            skip_special_tokens=True
        )

        generation_kwargs = dict(
            input_ids=input_ids,
            streamer=streamer,
            max_new_tokens=max_tokens,
            do_sample=temperature > 0.0,
            temperature=max(temperature, 0.01) if temperature > 0.0 else None,
            top_p=top_p if temperature > 0.0 else None,
            pad_token_id=self.tokenizer.pad_token_id,
            eos_token_id=self.tokenizer.eos_token_id,
        )

        # Run model generation in a dedicated thread to preserve async concurrency
        thread = threading.Thread(target=self.model.generate, kwargs=generation_kwargs)
        thread.start()

        # Non-blocking async queue consumer
        loop = asyncio.get_running_loop()
        
        def get_next_token():
            try:
                return next(streamer)
            except StopIteration:
                return None

        while True:
            # Run the blocking next() in threadpool executor so async event loop stays completely responsive
            token = await loop.run_in_executor(None, get_next_token)
            if token is None:
                break
            yield token

        thread.join()
